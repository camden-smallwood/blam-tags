/// Decode raw p8 / p8-bump pixels (one byte per pixel, each a palette index)
/// into RGBA8 (`[R, G, B, A]`), using the engine-appropriate palette. `out` must
/// be `input.len() * 4` bytes.
pub(super) fn decode_p8(input: &[u8], out: &mut [u8], palette: P8Palette) {
    let table = match palette {
        P8Palette::Halo1 => &P8_PALETTE_HALO1,
        P8Palette::Halo2 => &P8_PALETTE_HALO2,
    };
    for (px, &idx) in out.chunks_exact_mut(4).zip(input.iter()) {
        let [a, r, g, b] = table[idx as usize];
        px[0] = r;
        px[1] = g;
        px[2] = b;
        px[3] = a;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn halo2_entries_are_unit_normals_and_the_last_is_transparent() {
        for (index, [alpha, x, y, z]) in P8_PALETTE_HALO2[..255].iter().enumerate() {
            let axis = |value: &u8| f32::from(*value) / 255.0 * 2.0 - 1.0;
            let length = (axis(x).powi(2) + axis(y).powi(2) + axis(z).powi(2)).sqrt();
            assert!((length - 1.0).abs() < 0.02, "entry {index} has length {length}");
            assert_eq!(*alpha, 0xFF, "entry {index}");
        }
        // bitmap_palettize keeps index 255 for texels at or below half alpha.
        assert_eq!(P8_PALETTE_HALO2[255], [0x00, 0x80, 0x80, 0xFF]);
    }

    #[test]
    fn halo2_decode_keeps_the_cutout_in_alpha() {
        let mut out = [0u8; 8];
        decode_p8(&[1, 255], &mut out, P8Palette::Halo2);
        assert_eq!(out, [0x7E, 0x7F, 0xFF, 0xFF, 0x80, 0x80, 0xFF, 0x00]);
    }
}
