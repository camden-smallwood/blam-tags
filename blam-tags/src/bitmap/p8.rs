/// Decode raw p8 / p8-bump pixels (one byte per pixel, each a palette index)
/// into RGBA8 (`[R, G, B, A]`), using the engine-appropriate palette. `out` must
/// be `input.len() * 4` bytes.
pub(super) fn decode_p8(input: &[u8], out: &mut [u8], palette: P8Palette) {
    let table = match palette {
        P8Palette::Halo1 => &P8_PALETTE_HALO1,
        P8Palette::Halo2 => &P8_PALETTE_HALO2,
    };
    for (px, &idx) in out.chunks_exact_mut(4).zip(input.iter()) {
        let [a, r, g, b] = table[idx as usize];
        px[0] = r;
        px[1] = g;
        px[2] = b;
        px[3] = a;
    }
}
