//! Halo p8 / p8-bump normal-map palettes — the fixed 256-entry tables the
//! engine assigns palettized-normal indices against. **Halo 1 and Halo 2 use
//! different palettes** (240/256 entries differ), so the decode must be chosen
//! by engine.
//!
//! - `P8_PALETTE_HALO1`: Halo CE — verified byte-for-byte against Invader's
//!   `src/bitmap/p8/p8_palette` binary. Flat normal `(128,128,255)` at index 124.
//! - `P8_PALETTE_HALO2`: Halo 2 — the "spiral vector palette" tool's
//!   `generate_vector_palette` builds via `bitmap_generate_spiral_vector_palette`
//!   (`source\\bitmaps\\bitmap_palettes.cpp`): a 4x4 central grid of near-flat
//!   normals + a golden-angle spiral (`spiral_theta=137.5`, `maximum_phi=50`),
//!   index 255 a fixed special normal. Identical in the 2003 + MCC H2 tools
//!   (verified in IDA); matches TagTool's `BitmapConverterGen2.bumpPalette`.
//!   Flat `(128,128,255)` at index 10.
//!
//! Each entry is `[A, R, G, B]`; a raw p8 pixel indexes the table, normal = `rgb*2-1`.

/// Which engine's p8 palette to decode a palettized-normal bitmap with.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum P8Palette {
    /// Halo CE / Gen1.
    Halo1,
    /// Halo 2 / Gen2.
    Halo2,
}

